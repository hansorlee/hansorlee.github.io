#!/usr/bin/env python3

"""Sync missing Google Scholar publications into a generated BibTeX file.

This script preserves hand-edited entries in `_bibliography/papers.bib` and
writes only missing publications to `_bibliography/google-scholar-auto.bib`.
The generated file is meant to be consumed alongside `papers.bib` by
Jekyll-Scholar.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path

import yaml
from scholarly import scholarly

SOCIALS_FILE = Path("_data/socials.yml")
MANUAL_BIB_FILE = Path("_bibliography/papers.bib")
AUTO_BIB_FILE = Path("_bibliography/google-scholar-auto.bib")

AUTO_BIB_HEADER = """% This file is auto-generated by bin/sync_google_scholar_bibliography.py.
% Do not edit this file by hand. Add curated metadata to _bibliography/papers.bib instead.

"""

STOPWORDS = {
    "a",
    "an",
    "and",
    "for",
    "from",
    "in",
    "of",
    "on",
    "the",
    "to",
    "with",
}


@dataclass(frozen=True)
class ParsedEntry:
    key: str
    title: str
    google_scholar_id: str


def load_scholar_user_id() -> str:
    if not SOCIALS_FILE.exists():
        print(f"Configuration file {SOCIALS_FILE} not found.")
        sys.exit(1)

    with SOCIALS_FILE.open("r", encoding="utf-8") as handle:
        config = yaml.safe_load(handle) or {}

    scholar_user_id = config.get("scholar_userid")
    if not scholar_user_id:
        print(f"No 'scholar_userid' found in {SOCIALS_FILE}.")
        sys.exit(1)

    return scholar_user_id


def normalize_text(value: str) -> str:
    value = value or ""
    value = value.replace("\\&", "&")
    value = re.sub(r"\\[a-zA-Z]+\s*", " ", value)
    value = value.replace("{", "").replace("}", "")
    value = unicodedata.normalize("NFKD", value)
    value = value.encode("ascii", "ignore").decode("ascii")
    value = value.lower()
    value = re.sub(r"[^a-z0-9]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def normalize_title(title: str) -> str:
    return normalize_text(title)


def split_bibtex_entries(text: str) -> list[str]:
    entries: list[str] = []
    index = 0

    while True:
        start = text.find("@", index)
        if start == -1:
            break

        brace_start = text.find("{", start)
        if brace_start == -1:
            break

        depth = 0
        for cursor in range(brace_start, len(text)):
            char = text[cursor]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    entries.append(text[start : cursor + 1].strip())
                    index = cursor + 1
                    break
        else:
            break

    return entries


def extract_entry_key(block: str) -> str:
    match = re.match(r"@\w+\s*\{\s*([^,\s]+)\s*,", block)
    return match.group(1).strip() if match else ""


def extract_field_value(block: str, field_name: str) -> str:
    pattern = re.compile(rf"(?im)^\s*{re.escape(field_name)}\s*=\s*")
    match = pattern.search(block)
    if not match:
        return ""

    cursor = match.end()
    while cursor < len(block) and block[cursor].isspace():
        cursor += 1

    if cursor >= len(block):
        return ""

    opener = block[cursor]
    if opener in {'"', "{"}:
        closer = '"' if opener == '"' else "}"
        cursor += 1
        start = cursor
        depth = 1 if opener == "{" else 0

        while cursor < len(block):
            char = block[cursor]
            if opener == "{":
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                    if depth == 0:
                        return block[start:cursor].strip()
            elif char == '"' and block[cursor - 1] != "\\":
                return block[start:cursor].strip()
            cursor += 1

        return ""

    end = cursor
    while end < len(block) and block[end] not in {",", "\n"}:
        end += 1
    return block[cursor:end].strip()


def parse_bib_entries(path: Path) -> list[ParsedEntry]:
    if not path.exists():
        return []

    text = path.read_text(encoding="utf-8")
    parsed_entries: list[ParsedEntry] = []

    for block in split_bibtex_entries(text):
        key = extract_entry_key(block)
        title = extract_field_value(block, "title")
        google_scholar_id = extract_field_value(block, "google_scholar_id")
        parsed_entries.append(
            ParsedEntry(key=key, title=title, google_scholar_id=google_scholar_id)
        )

    return parsed_entries


def clean_value(value: str) -> str:
    return re.sub(r"\s+", " ", (value or "")).strip()


def bibtex_escape(value: str) -> str:
    value = clean_value(value)
    value = value.replace("\\", "\\\\")
    return value.replace("{", "\\{").replace("}", "\\}")


def parse_scholar_publication_id(publication: dict) -> str:
    publication_id = publication.get("author_pub_id") or ""
    if ":" in publication_id:
        return publication_id.split(":", 1)[1]
    return publication_id


def format_authors(author_value: str | list[str]) -> str:
    if isinstance(author_value, list):
        authors = [clean_value(author) for author in author_value if clean_value(author)]
        return " and ".join(authors)

    author_text = clean_value(author_value)
    if not author_text:
        return ""
    if " and " in author_text:
        return author_text

    authors = [part.strip() for part in author_text.split(",") if part.strip()]
    if len(authors) <= 1:
        return author_text
    return " and ".join(authors)


def infer_entry_type(bib: dict) -> str:
    pub_type = clean_value(bib.get("pub_type", "")).lower()
    if pub_type in {
        "article",
        "book",
        "inbook",
        "incollection",
        "inproceedings",
        "manual",
        "mastersthesis",
        "misc",
        "phdthesis",
        "techreport",
    }:
        return pub_type

    source_text = " ".join(
        clean_value(part)
        for part in [bib.get("journal"), bib.get("venue"), bib.get("citation")]
        if clean_value(part)
    ).lower()

    if any(
        token in source_text
        for token in ["conference", "proceedings", "symposium", "workshop", "meeting"]
    ):
        return "inproceedings"

    return "article"


def extract_first_author_last_name(authors: str) -> str:
    if not authors:
        return "publication"

    first_author = authors.split(" and ", 1)[0].strip()
    if "," in first_author:
        candidate = first_author.split(",", 1)[0]
    else:
        candidate = first_author.split()[-1]

    normalized = re.sub(r"[^a-z0-9]+", "", normalize_text(candidate))
    return normalized or "publication"


def choose_key_word(title: str) -> str:
    for word in normalize_title(title).split():
        if len(word) > 2 and word not in STOPWORDS:
            return word
    words = normalize_title(title).split()
    return words[0] if words else "paper"


def make_unique_key(base_key: str, used_keys: set[str]) -> str:
    if base_key not in used_keys:
        used_keys.add(base_key)
        return base_key

    suffix = 2
    while f"{base_key}{suffix}" in used_keys:
        suffix += 1

    unique_key = f"{base_key}{suffix}"
    used_keys.add(unique_key)
    return unique_key


def extract_arxiv_id(*candidates: str) -> str:
    patterns = [
        r"arxiv\.org/(?:abs|pdf)/([a-z\-]+/\d{7}|\d{4}\.\d{4,5})(?:v\d+)?",
        r"arxiv[:\s]+([a-z\-]+/\d{7}|\d{4}\.\d{4,5})(?:v\d+)?",
    ]

    for candidate in candidates:
        for pattern in patterns:
            match = re.search(pattern, candidate or "", flags=re.IGNORECASE)
            if match:
                return match.group(1)
    return ""


def build_entry_lines(publication: dict, key: str) -> list[str]:
    bib = publication.get("bib", {}) or {}
    entry_type = infer_entry_type(bib)
    authors = format_authors(bib.get("author", ""))
    scholar_id = parse_scholar_publication_id(publication)

    title = clean_value(bib.get("title", ""))
    year = clean_value(bib.get("pub_year", ""))
    venue = clean_value(bib.get("venue", ""))
    journal = clean_value(bib.get("journal", "")) or venue
    publisher = clean_value(bib.get("publisher", ""))
    volume = clean_value(bib.get("volume", ""))
    number = clean_value(bib.get("number", ""))
    pages = clean_value(bib.get("pages", ""))
    citation = clean_value(bib.get("citation", ""))

    pub_url = clean_value(publication.get("pub_url", ""))
    eprint_url = clean_value(publication.get("eprint_url", ""))
    arxiv_id = extract_arxiv_id(pub_url, eprint_url, journal, venue, citation)

    fields: list[tuple[str, str]] = [
        ("title", title),
        ("author", authors),
    ]

    if entry_type == "inproceedings":
        fields.append(("booktitle", venue or journal))
    elif entry_type == "incollection":
        fields.append(("booktitle", venue or journal))
        if publisher:
            fields.append(("publisher", publisher))
    elif entry_type == "book":
        if publisher:
            fields.append(("publisher", publisher))
    else:
        fields.append(("journal", journal))

    for field_name, value in [
        ("volume", volume),
        ("number", number),
        ("pages", pages),
        ("year", year),
    ]:
        if value:
            fields.append((field_name, value))

    if publisher and entry_type not in {"book", "incollection"}:
        fields.append(("publisher", publisher))

    if arxiv_id:
        fields.append(("arxiv", arxiv_id))

    preferred_html = pub_url if pub_url and "scholar.google" not in pub_url else eprint_url
    if preferred_html:
        fields.append(("html", preferred_html))

    if scholar_id:
        fields.append(("google_scholar_id", scholar_id))

    lines = [f"@{entry_type}{{{key},"]
    for field_name, value in fields:
        if value:
            lines.append(f"  {field_name}={{{bibtex_escape(value)}}},")
    lines.append("}")
    return lines


def fetch_author_publications(scholar_user_id: str) -> list[dict]:
    scholarly.set_timeout(15)
    scholarly.set_retries(3)

    author = scholarly.search_author_id(scholar_user_id)
    author_data = scholarly.fill(author)
    publications = author_data.get("publications", [])
    if not publications:
        print(f"No publications found for Google Scholar user '{scholar_user_id}'.")
        return []

    filled_publications: list[dict] = []
    for publication in publications:
        try:
            filled_publications.append(scholarly.fill(publication))
        except Exception:
            filled_publications.append(publication)

    return filled_publications


def build_generated_bibliography(dry_run: bool) -> int:
    scholar_user_id = load_scholar_user_id()
    manual_entries = parse_bib_entries(MANUAL_BIB_FILE)
    existing_auto_entries = parse_bib_entries(AUTO_BIB_FILE)

    manual_titles = {
        normalize_title(entry.title) for entry in manual_entries if normalize_title(entry.title)
    }
    auto_key_by_scholar_id = {
        entry.google_scholar_id: entry.key
        for entry in existing_auto_entries
        if entry.google_scholar_id and entry.key
    }
    auto_key_by_title = {
        normalize_title(entry.title): entry.key
        for entry in existing_auto_entries
        if normalize_title(entry.title) and entry.key
    }

    used_keys = {
        entry.key
        for entry in [*manual_entries, *existing_auto_entries]
        if entry.key
    }

    publications = fetch_author_publications(scholar_user_id)
    generated_entries: list[tuple[tuple[int, str], str, str]] = []
    seen_generated_titles: set[str] = set()
    seen_generated_scholar_ids: set[str] = set()

    for publication in publications:
        bib = publication.get("bib", {}) or {}
        title = clean_value(bib.get("title", ""))
        if not title:
            continue

        normalized = normalize_title(title)
        if not normalized or normalized in manual_titles:
            continue

        scholar_id = parse_scholar_publication_id(publication)
        if normalized in seen_generated_titles:
            continue
        if scholar_id and scholar_id in seen_generated_scholar_ids:
            continue

        existing_key = auto_key_by_scholar_id.get(scholar_id) or auto_key_by_title.get(normalized)

        if existing_key:
            key = existing_key
            used_keys.add(key)
        else:
            authors = format_authors(bib.get("author", ""))
            year = clean_value(bib.get("pub_year", "")) or "nodate"
            base_key = f"{extract_first_author_last_name(authors)}{year}{choose_key_word(title)}"
            key = make_unique_key(base_key, used_keys)

        year_value = clean_value(bib.get("pub_year", ""))
        year_sort = -int(year_value) if year_value.isdigit() else 0
        generated_entries.append(
            (
                (year_sort, normalized),
                "\n".join(build_entry_lines(publication, key)),
                title,
            )
        )
        seen_generated_titles.add(normalized)
        if scholar_id:
            seen_generated_scholar_ids.add(scholar_id)

    generated_entries.sort(key=lambda item: item[0])
    generated_blocks = [block for _, block, _ in generated_entries]
    added_titles = [title for _, _, title in generated_entries]
    output_text = AUTO_BIB_HEADER
    if generated_blocks:
        output_text += "\n\n".join(generated_blocks) + "\n"

    if dry_run:
        print(f"Would write {len(generated_blocks)} generated entries to {AUTO_BIB_FILE}.")
        for title in added_titles:
            print(f" - {title}")
        return 0

    AUTO_BIB_FILE.parent.mkdir(parents=True, exist_ok=True)
    AUTO_BIB_FILE.write_text(output_text, encoding="utf-8")
    print(f"Wrote {len(generated_blocks)} generated entries to {AUTO_BIB_FILE}.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate a Google Scholar-managed BibTeX file for missing publications."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the entries that would be written without modifying files.",
    )
    args = parser.parse_args()

    try:
        return build_generated_bibliography(dry_run=args.dry_run)
    except Exception as exc:
        print(f"Unexpected error while syncing Google Scholar bibliography: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
